public class nine{
    public static void main(String[] args) {
        int i=12;
        while (i<11) {
            System.out.println(i);
            i++;
        }
        do{
            System.out.println(i);
            i++;
        }while(i<11);
    }
    // this program is an example of do while which prints an output even if the condition is wrong
}